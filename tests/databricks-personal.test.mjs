import assert from 'node:assert/strict';
import {settings,run} from '../scripts/databricks-personal.mjs';
const env={DATABRICKS_HOST:'https://dbc-example.cloud.databricks.com',DATABRICKS_TOKEN:'test-secret',DATABRICKS_JOB_ID:'42',GITHUB_RUN_ID:'99'};
const job={settings:{max_concurrent_runs:1,timeout_seconds:900,tasks:[{task_key:'personal_agent',max_retries:0,notebook_task:{notebook_path:'/Workspace/personal_agent'}}]}};
for(const host of ['http://dbc-example.cloud.databricks.com','https://dbc-example.cloud.databricks.com.evil.test','https://user@dbc-example.cloud.databricks.com','https://dbc-example.cloud.databricks.com/?token=x']) assert.throws(()=>settings({...env,DATABRICKS_HOST:host}));
assert.throws(()=>settings({...env,DATABRICKS_TOKEN:''}));
let calls=[],logs=[];
const replies=[job,{run_id:12},{state:{life_cycle_state:'TERMINATED',result_state:'SUCCESS'}}];
await run(env,async(url,options)=>{calls.push({url,options});return {ok:true,json:async()=>replies.shift()};},async()=>{},s=>logs.push(s));
assert.equal(calls.length,3);
assert.equal(JSON.parse(calls[1].options.body).idempotency_token,'side-quest-99');
assert(calls.every(c=>c.options.redirect==='error'));
assert(!logs.join('').includes('test-secret'));
assert(!calls.some(c=>c.url.includes('get-output')));
const paid=structuredClone(job);paid.settings.tasks[0].new_cluster={};
await assert.rejects(()=>run(env,async()=>({ok:true,json:async()=>paid}),async()=>{},()=>{}),/serverless/);
await assert.rejects(()=>run(env,async()=>({ok:false,status:429}),async()=>{},()=>{}),/HTTP 429/);
let n=0;
await assert.rejects(()=>run(env,async()=>({ok:true,json:async()=>[job,{run_id:12},{state:{life_cycle_state:'TERMINATED',result_state:'FAILED'}}][n++]}),async()=>{},()=>{}),/did not succeed/);
let cancelled=false,count=0;
await assert.rejects(()=>run(env,async(url)=>{count++;if(url.endsWith('/cancel'))cancelled=true;return {ok:true,json:async()=>count===1?job:count===2?{run_id:12}:{state:{life_cycle_state:'RUNNING'}}};},async()=>{},()=>{}),/Cancellation requested/);
assert(cancelled);
console.log('Databricks bridge tests passed.');
